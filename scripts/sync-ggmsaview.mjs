/**
 * Writes docs/r-package.md, the site's /r-package page, from a ggmsaview
 * checkout: its README, with the gallery table replaced by each example's
 * figure pair and recipe from docs/gallery.md. The gallery images go to
 * docs/media as ggmsaview-<example>-{viewer,r}.webp, so run `pnpm media:push`
 * after it.
 *
 *   node scripts/sync-ggmsaview.mjs [path/to/ggmsaview]
 *
 * The path defaults to GGMSAVIEW, then ../ggmsaview beside this checkout.
 */
import { execFileSync } from 'node:child_process'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const repoRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '..',
)
const gg = path.resolve(
  process.argv[2] ??
    process.env.GGMSAVIEW ??
    path.join(repoRoot, '..', 'ggmsaview'),
)
const site = 'https://gmod.org/JBrowseMSA'
const out = path.join(repoRoot, 'docs', 'r-package.md')
const mediaDir = path.join(repoRoot, 'docs', 'media')

const read = f => fs.readFileSync(path.join(gg, f), 'utf8')
const commit = execFileSync('git', ['-C', gg, 'rev-parse', 'HEAD'], {
  encoding: 'utf8',
}).trim()

// Splits markdown into its `## ` sections, skipping `#` lines inside fences
function sections(md) {
  const result = [{ heading: '', lines: [] }]
  let fenced = false
  for (const line of md.split('\n')) {
    if (line.startsWith('```')) {
      fenced = !fenced
    }
    if (!fenced && line.startsWith('## ')) {
      result.push({ heading: line.slice(3), lines: [] })
    } else {
      result.at(-1).lines.push(line)
    }
  }
  return result
}

function galleryExamples(md) {
  return sections(md)
    .slice(1)
    .map(({ heading, lines }) => {
      const body = lines.join('\n')
      const imgs = [
        ...body.matchAll(/<img src="\.\.\/gallery\/([^"]+)" alt="([^"]+)"/g),
      ]
      const recipe = /```r\n[\s\S]*?\n```/.exec(body)
      const caption = lines.find(l => l.trim() && !/^[<`]/.test(l))
      if (imgs.length !== 2 || !recipe || !caption) {
        throw new Error(`gallery.md: cannot read the example "${heading}"`)
      }
      return { title: heading, imgs, caption, recipe: recipe[0] }
    })
}

function copyImage(file) {
  const name = `ggmsaview-${file}`
  fs.mkdirSync(mediaDir, { recursive: true })
  fs.copyFileSync(path.join(gg, 'gallery', file), path.join(mediaDir, name))
  return `media/${name}`
}

function gallerySection(examples) {
  const figures = examples.flatMap(({ title, imgs, caption, recipe }) => [
    `### ${title}`,
    '',
    imgs.map(([, file, alt]) => `![${alt}](${copyImage(file)})`).join(' '),
    '',
    caption,
    '',
    '<details>',
    '<summary>Recipe</summary>',
    '',
    recipe,
    '',
    '</details>',
    '',
  ])
  return [
    '',
    '- Each figure is drawn twice from data installed with the package:',
    "  JBrowseMSA's own SVG export (`msaview_save()`) on the left,",
    '  `msaview_plot()` on the right.',
    '- Each recipe runs as written after',
    '',
    '  ```r',
    '  library(ggmsaview)',
    '  e <- function(f) system.file("extdata", f, package = "ggmsaview")',
    '  ```',
    '',
    ...figures,
  ]
}

const dropped = new Set(['Development', 'License'])
const examples = galleryExamples(read('docs/gallery.md'))
const [intro, ...rest] = sections(read('README.md'))

const body = [
  ...intro.lines.map(l => l.replace(/^# ggmsaview$/, '# R package')),
  ...rest
    .filter(s => !dropped.has(s.heading))
    .flatMap(s => [
      `## ${s.heading}`,
      ...(s.heading === 'Gallery' ? gallerySection(examples) : s.lines),
    ]),
]
  .join('\n')
  .replaceAll(`${site}/media/`, 'media/')
  .replaceAll('](../cli/)', `](${site}/cli)`)
  .replaceAll('](https://github.com/GMOD/JBrowseMSA)', `](${site})`)
  .replace(/\n{3,}/g, '\n\n')
  .trimEnd()

fs.writeFileSync(
  out,
  `<!-- Generated by scripts/sync-ggmsaview.mjs from GMOD/ggmsaview@${commit.slice(0, 7)}. Edit ggmsaview's README or scripts/gallery.R, then rerun it. -->\n\n${body}\n`,
)
execFileSync('pnpm', ['exec', 'oxfmt', out], { cwd: repoRoot })
console.log(
  `wrote ${path.relative(repoRoot, out)} with ${examples.length} gallery examples from ggmsaview@${commit.slice(0, 7)}`,
)
